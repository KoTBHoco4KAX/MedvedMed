export function greeting(firstName: string): string {
  const name = firstName.trim()
  return name === '' ? 'Здравствуйте' : `Привет, ${name}`
}

export type UrgencyTone = 'emergency' | 'urgent' | 'planned' | 'self_care'

export function urgencyTone(urgency: string): UrgencyTone {
  const value = urgency.trim().toLowerCase()
  if (value === 'emergency' || value.startsWith('экстрен') || value.startsWith('немедлен')) return 'emergency'
  if (value === 'urgent_24h' || value.startsWith('срочно')) return 'urgent'
  if (value === 'self_care' || value.startsWith('самопомощ') || value.includes('наблюдение дома')) return 'self_care'
  return 'planned'
}

// Коды срочности приходят из LLM ("emergency" / "urgent_24h" / "planned" / "self_care"),
// в старых консультациях могут лежать русские формулировки — показываем подпись в обоих случаях.
export function urgencyLabel(urgency: string): string {
  switch (urgencyTone(urgency)) {
    case 'emergency':
      return 'Экстренно — вызовите скорую (103/112)'
    case 'urgent':
      return 'Срочно (в течение 24 часов)'
    case 'self_care':
      return 'Самопомощь / наблюдение дома'
    default:
      return 'Планово (в течение 3–5 дней)'
  }
}

// Бейдж без рамки и подложки — срочность передаётся цветом текста и эмодзи.
export function urgencyTextClass(tone: UrgencyTone): string {
  switch (tone) {
    case 'emergency':
      return 'text-red-700'
    case 'urgent':
      return 'text-amber-800'
    case 'self_care':
      return 'text-emerald-700'
    default:
      return 'text-ink'
  }
}

export function urgencyEmoji(tone: UrgencyTone): string {
  switch (tone) {
    case 'emergency':
      return '🚨'
    case 'urgent':
      return '⏱️'
    case 'self_care':
      return '🏡'
    default:
      return '🗓️'
  }
}

export function formatDateTime(iso: string): string {
  const date = new Date(iso)
  if (Number.isNaN(date.getTime())) return ''
  return new Intl.DateTimeFormat('ru-RU', {
    day: 'numeric',
    month: 'long',
    hour: '2-digit',
    minute: '2-digit',
  }).format(date)
}
